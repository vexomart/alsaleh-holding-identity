/**
 * Get articles subset for compact display
 */
export function getCompactArticles(): LegalArticle[] {
  return FINANCE_CONTRACT_ARTICLES.filter(
    (a) => [1, 2, 3, 4, 5, 6, 8, 12].includes(a.number)
  );
}

/**
 * Format article number in Arabic
 */
export function formatArticleNumber(num: number): string {
  const arabicOrdinals = [
    '', 'الأولى', 'الثانية', 'الثالثة', 'الرابعة', 'الخامسة',
    'السادسة', 'السابعة', 'الثامنة', 'التاسعة', 'العاشرة',
    'الحادية عشرة', 'الثانية عشرة',
  ];
  return `المادة ${arabicOrdinals[num] || num}`;
}
